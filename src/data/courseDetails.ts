/**
 * 교육과정 세부내용 — /courses/{slug}/
 * 원본: buildup.oopy.io 의 각 과정 상세 페이지 (2026-09 캡처). 문구는 원본 그대로, 항목은 하나도 빼지 않는다.
 *
 * 다섯 가지 유형이 있어서 블록을 선택적으로 둔다.
 *   1day 세미나   : intro(why · contents · recommend) → features → flow → fee → guide
 *   강점세미나     : quote → intro.blocks(What/Why/진단/코칭) → features → flow → fee → guide(+book) → voices
 *   커플코칭스쿨   : intro.blocks(과정설명) → features → curriculum → flow → diagnosis → guide → book → fee → voices
 *   Happy New Year : intro → curriculum(6대 시스템) → features → flow → fee → guide → voices  (kind 는 oneday — 1day 세미나 블록에 함께 보인다)
 *   영성일기       : intro.blocks(과정설명) → curriculum(6주) → flow(130분) → guide → book → fee → voices  (features 없음)
 *                    원본은 oopy 가 아니라 buildup365.notion.site 의 "2026년 빌드업 연간교육일정" DB (assets/source/oopy-courses/하나님과의-친밀감-영성일기-*.txt)
 *
 * status 'soon'(추후모집) 인 항목은 start 를 비워 둘 수 있다. 목록에는 "일정 추후 공지"로 보이고 타임라인에는 나오지 않는다.
 */
import type { CourseKind, CourseStatus } from './types';

export interface LinkCard {
  label: string;
  href: string;
  desc?: string;
  /** 책 표지 등 썸네일 (public/ 경로) */
  image?: string;
}
export interface CourseBlock {
  title: string;
  paras?: string[];
  bullets?: string[];
  links?: LinkCard[];
  stats?: { value: string; label: string }[];
  options?: { title: string; items: string[] }[];
  note?: string;
}
export interface CourseDetail {
  slug: string;
  /** 정기 교육과정 목록(/teaching/)에 보이는 제목 */
  courseTitle: string;
  /** 프로그램 종류 — /teaching/ 의 블록·타임라인 행을 결정 */
  kind: CourseKind;
  /** 시작일 · 종료일(ISO). 목록·타임라인·세부 페이지가 모두 여기서 계산한다. status 가 'soon' 이면 비워 둘 수 있다 */
  start?: string;
  end?: string;
  series: string;
  name: string;
  eyebrow: string;
  /** 모집 상태 — 여기 한 곳만 바꾸면 목록·타임라인·세부 페이지가 함께 바뀐다 */
  status: CourseStatus;
  /** 이 과정의 참가신청서 */
  form: string;
  /** 원본 속성 표 — 순서 그대로 */
  props: {
    time: string;
    format: string;
    fee: { list: string; sale: string; note?: string };
    instructor: string;
    audience: string;
    deadline: string;
    capacity?: string;
  };
  quote?: { text: string; by: string };
  intro: {
    headline: string;
    lead?: string;
    why?: { title: string; text: string };
    blocks?: CourseBlock[];
    contents?: { title: string; lead?: string; items: { title: string; text: string }[] };
    recommend?: { title: string; items: string[] };
  };
  /** 과정 특징 스티커. 원본에 없는 과정(영성일기)은 생략한다 */
  features?: { title: string; text: string }[];
  curriculum?: { title: string; note?: string; items: { title: string; text?: string }[] };
  flow: { title: string; steps: string[] };
  diagnosis?: { title: string; text: string };
  fee: { title: string; text: string; extra?: string[] };
  book?: { title: string; text: string; link: LinkCard };
  guide: { title: string; items: { icon: string; title: string; text: string }[]; notes?: string[]; links?: LinkCard[] };
  instructorTitle?: string;
  instructorItems?: string[];
  apply?: { title?: string; intro?: string; depositName?: string; after?: string; notes?: string[] };
  voices?: { title: string; items: { text: string; by: string }[]; links?: LinkCard[] };
}

